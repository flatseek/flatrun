class MmapTensorHandle(TensorHandle):
    """Handle backed by an mmap slice of the source file."""

    __slots__ = ("_mmap", "_offset", "_dtype", "_shape")

    def __init__(
        self,
        metadata: TensorMetadata,
        mmap_obj: mmap.mmap,
        *,
        offset: int,
    ) -> None:
        super().__init__(metadata, HandleSource.MMAP)
        self._mmap = mmap_obj
        self._offset = int(offset)
        self._dtype = storage_dtype(metadata.dtype)
        self._shape = tuple(metadata.shape)

    def view(self) -> TensorView:
        if self._closed:
            raise RuntimeError(f"Handle {self.name!r} is closed")
        # The mmap object's slice produces a zero-copy view.
        slice_obj = self._mmap[self._offset : self._offset + self.byte_size]
        arr = np.ndarray(
            shape=self._shape,
            dtype=self._dtype,
            buffer=slice_obj,
            order="C",
        )
        arr.flags.writeable = False
        if is_bfloat16(self._metadata.dtype):
            # Widening allocates; bfloat16 cannot be viewed in place.
            return TensorView(
                data=bfloat16_to_float32(arr),
                shape=self._shape,
                dtype="float32",
            )
        return TensorView(data=arr, shape=self._shape, dtype=self._metadata.dtype)

    def materialize(self) -> bytes:
        """Return raw bytes from the mmap region.

        We bypass :meth:`view` for mmap handles because the numpy view
        only exposes ``numel * itemsize`` bytes - the mmap region can
        be longer when the dtype is quantised (the on-disk block size
        differs from the logical element count).
        """
        if self._closed:
            raise RuntimeError(f"Handle {self.name!r} is closed")
        # ``mmap[i:j]`` returns a new mmap slice object; ``bytes()`` of
        # that materialises the requested range into a real byte array.
        return bytes(self._mmap[self._offset : self._offset + self.byte_size])

    def _close_native(self) -> None:
        # Hint the kernel to drop the mmap pages for this region.
        #
        # Without this hint the pages stay in the page cache (and count
        # toward RSS) for the entire process lifetime once they have been
        # touched. The backend keeps the parent mmap alive for the
        # duration of inference, so even ``close()`` on the handle does
        # not unmap the region. For very large models (>= 14B in Q4_K,
        # 27B+, ...) the cumulative page cache can grow past several GB
        # before the model is fully streamed, which is enough to OOM
        # memory-constrained hosts even though the scheduler logically
        # "released" the layer.
        #
        # Trade-off: ``MADV_DONTNEED`` is page-aligned. If two small
        # tensors share a 4 KiB page, the kernel may discard the page
        # for both tensors even though only one was released. The next
        # access of the still-resident tensor re-faults from disk -
        # cheap for layer-sized tensors, measurable for tiny ones.
        # We only call madvise for tensors >= 1 MiB so the alignment
        # cost is bounded.
        if self._mmap is not None and self.byte_size >= 1024 * 1024:
            try:
                madv_dontneed = getattr(mmap, "MADV_DONTNEED", None)
                if madv_dontneed is not None:
                    self._mmap.madvise(madv_dontneed, self._offset, self.byte_size)
            except Exception:
                # madvise is best-effort. If the kernel rejects the
                # hint (some FUSE mounts, exotic filesystems), fall
                # back to the old behaviour - the page stays resident
                # until the backend closes.
                pass
        # We don't own the mmap - the backend closes it. Just drop the ref.
        self._mmap = None  # type: ignore[assignment]


class BufferTensorHandle(TensorHandle):
    """Handle backed by an in-RAM ``bytes`` or ``bytearray`` buffer.

    Used for small tensors, fully-decoded quantized blocks, and as a
    fallback when the host filesystem doesn't support mmap (e.g. some
    FUSE mounts).
    """

    __slots__ = ("_buffer",)

    def __init__(self, metadata: TensorMetadata, buffer: bytes | bytearray) -> None:
        super().__init__(metadata, HandleSource.BUFFER)
        self._buffer = buffer

    def view(self) -> TensorView:
        if self._closed:
            raise RuntimeError(f"Handle {self.name!r} is closed")
        # No copy. ``np.frombuffer`` shares memory with the underlying buffer.
        shape = self._metadata.shape
        raw_dtype = storage_dtype(self._metadata.dtype)
        arr = np.frombuffer(self._buffer, dtype=raw_dtype)
        if arr.size != int(np.prod(shape)):
            return TensorView(data=bytes(self._buffer), shape=shape, dtype=self._metadata.dtype)
        if is_bfloat16(self._metadata.dtype):
            return TensorView(
                data=bfloat16_to_float32(arr).reshape(shape),
                shape=shape,
                dtype="float32",
            )
        return TensorView(data=arr.reshape(shape), shape=shape, dtype=self._metadata.dtype)

    def _close_native(self) -> None:
        self._buffer = b""


